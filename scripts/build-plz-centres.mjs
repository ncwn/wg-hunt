//   curl -LO https://download.geonames.org/export/zip/DE.zip && unzip DE.zip DE.txt
//   node scripts/build-plz-centres.mjs path/to/DE.txt
//
// A PLZ with several places gets the plain average of their positions, to three decimals (about
// 100 m), which is as precise as a postal-code centre can honestly be.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const input = process.argv[2];
if (!input) {
  console.error("usage: node scripts/build-plz-centres.mjs path/to/DE.txt");
  process.exit(1);
}

const sums = new Map();
for (const line of readFileSync(input, "utf8").split("\n")) {
  const columns = line.split("\t");
  const [country, plz] = columns;
  const lat = Number(columns[9]);
  const lng = Number(columns[10]);
  if (country !== "DE" || !/^\d{5}$/.test(plz ?? "") || !Number.isFinite(lat + lng)) continue;
  const sum = sums.get(plz) ?? { lat: 0, lng: 0, count: 0 };
  sums.set(plz, { lat: sum.lat + lat, lng: sum.lng + lng, count: sum.count + 1 });
}

const round = (value) => Math.round(value * 1000) / 1000;
const lines = [...sums.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([plz, { lat, lng, count }]) => `${plz} ${round(lat / count)} ${round(lng / count)}`);

const out = join(
  dirname(fileURLToPath(import.meta.url)),
  "../packages/core/src/places/plz-centres.ts",
);
const header = `// Generated by scripts/build-plz-centres.mjs from the GeoNames postal-code data for Germany.
// © GeoNames (https://www.geonames.org), licensed CC BY 4.0: see LICENSE.md in this folder.
// One PLZ per line: "<PLZ> <latitude> <longitude>".
`;
writeFileSync(out, `${header}export const PLZ_CENTRES = \`${lines.join("\n")}\n\`;\n`);
console.log(`${lines.length} PLZ centres written`);
